package ru.afina.gosklyuch;

/**
 * Источник маркера доступа ЕПГУ (значение заголовка авторизации).
 *
 * <p>Маркер выдаётся организации-вендору при подключении к API ЕПГУ
 * и должен храниться вне кода: в конфигурации/секрете инсталляции.
 * Интерфейс позволяет подменить источник (файл, vault, сервис) без
 * изменения клиента API.</p>
 */
public interface GosklyuchTokenProvider {

    /**
     * Текущий маркер доступа.
     *
     * @throws GosklyuchUnavailableException если маркер не настроен
     */
    String token();
}
