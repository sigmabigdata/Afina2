package ru.afina.gosklyuch;

/**
 * Подписывает файлы пакета заявки отсоединённой УКЭП организации
 * (PKCS#7, DER) — требование спецификации Госключа: и {@code req.xml},
 * и каждый документ архива подписываются УКЭП.
 *
 * <p>Реализация зависит от инсталляции (ключевой носитель, КриптоПро CSP,
 * сертификат организации), поэтому в Phase 1 интерфейс не имеет
 * криптографической реализации: бин {@link GosklyuchSignerUnavailable}
 * явно сообщает, что подписание пакета не настроено. Пока подписант
 * недоступен, отправка заявок запрещена на уровне сервиса.</p>
 */
public interface GosklyuchSigner {

    /**
     * Построить отсоединённую подпись PKCS#7 (DER) для содержимого файла.
     *
     * @param fileName имя файла в архиве (для диагностики)
     * @param content  содержимое файла
     * @return подпись в формате PKCS#7 DER
     */
    byte[] signDetached(String fileName, byte[] content);
}
